import * as vscode from 'vscode';
import * as path from 'path';
import { TourFile, resolveStepUri } from './model';

/** Render a tour as a standalone Markdown document with code excerpts. */
export async function tourToMarkdown(file: TourFile): Promise<string> {
  const { tour } = file;
  const lines: string[] = [`# ${tour.title}`, ''];
  if (tour.description) lines.push(tour.description, '');
  lines.push(`_${tour.steps.length} steps${tour.createdBy ? ` · generated by ${tour.createdBy}` : ''}${tour.diffRef ? ` · \`git diff ${tour.diffRef}\`` : ''}_`, '');

  for (const [i, step] of tour.steps.entries()) {
    const end = step.endLine ?? step.line;
    lines.push(`## ${i + 1}. ${step.title}`, '');
    lines.push(`\`${step.file}:${step.line}${end !== step.line ? '-' + end : ''}\``, '');
    lines.push(step.body.trim(), '');
    const snippet = await readLines(resolveStepUri(file.uri, step), step.line, end);
    if (snippet !== undefined) {
      lines.push('```' + languageFor(step.file), snippet, '```', '');
    }
  }
  return lines.join('\n');
}

async function readLines(uri: vscode.Uri, from: number, to: number): Promise<string | undefined> {
  try {
    const doc = await vscode.workspace.openTextDocument(uri);
    const a = Math.max(1, from), b = Math.min(doc.lineCount, to);
    if (a > b) return undefined;
    return doc.getText(new vscode.Range(a - 1, 0, b - 1, doc.lineAt(b - 1).text.length));
  } catch {
    return undefined;
  }
}

function languageFor(file: string): string {
  const ext = path.extname(file).slice(1).toLowerCase();
  const map: Record<string, string> = {
    ts: 'typescript', tsx: 'tsx', js: 'javascript', jsx: 'jsx', mjs: 'javascript', cjs: 'javascript',
    py: 'python', rb: 'ruby', go: 'go', rs: 'rust', java: 'java', kt: 'kotlin', swift: 'swift',
    c: 'c', h: 'c', cpp: 'cpp', cc: 'cpp', hpp: 'cpp', cs: 'csharp', php: 'php', sh: 'bash', zsh: 'bash',
    yml: 'yaml', yaml: 'yaml', json: 'json', md: 'markdown', html: 'html', css: 'css', scss: 'scss', sql: 'sql', toml: 'toml'
  };
  return map[ext] ?? ext;
}
